#!/usr/bin/env python3
"""Render tool adapters from shared prompts and explicit adapter metadata."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys


def quoted(value: str) -> str:
    """JSON basic strings also safely encode our TOML/YAML string values."""
    return json.dumps(value, ensure_ascii=False)


def codex_text(value: str, workflows: list[str]) -> str:
    value = value.replace("view_file / grep_search", "file-reading tools and rg searches")
    for name in workflows:
        value = value.replace(f"/{name}", f"${name}")
    return value


def render(root: Path) -> dict[Path, str]:
    """Return deterministic relative paths and content without modifying files."""
    outputs: dict[Path, str] = {}
    workflow_dirs = sorted((root / "workflows").glob("*/BODY.md"))
    workflow_names = [body.parent.name for body in workflow_dirs]
    for source in sorted((root / "agents").glob("*/PROMPT.md")):
        directory = source.parent
        name = directory.name
        prompt = source.read_text()
        description = (directory / "DESCRIPTION.txt").read_text().strip()
        metadata = json.loads((directory / "metadata.json").read_text())
        for tool, template in metadata["legacy_templates"].items():
            outputs[Path("agents") / name / f"{tool}.md"] = template.replace(
                "{{DESCRIPTION}}", description
            ).replace("{{PROMPT}}", prompt)
        instructions = codex_text(prompt, workflow_names)
        if metadata["skills"]:
            instructions += "\n# Required skills\nBefore starting, read the SKILL.md instructions for these installed skills: "
            instructions += ", ".join(f"`{skill}`" for skill in metadata["skills"]) + ".\n"
        fields = {"name": name, "description": description, "developer_instructions": instructions}
        content = "# Generated by scripts/build_kit.py; edit shared sources instead.\n"
        content += "".join(f"{key} = {quoted(value)}\n" for key, value in fields.items())
        if metadata["read_only"]:
            content += 'sandbox_mode = "read-only"\n'
        outputs[Path("agents") / name / "codex.toml"] = content
    for source in workflow_dirs:
        directory = source.parent
        name = directory.name
        body = source.read_text()
        metadata = json.loads((directory / "metadata.json").read_text())
        for tool, template in metadata["legacy_templates"].items():
            outputs[Path("workflows") / name / f"{tool}.md"] = template.replace("{{BODY}}", body)
        skill = f"---\nname: {name}\ndescription: {quoted(metadata['description'])}\n---\n\n"
        skill += codex_text(body, workflow_names)
        outputs[Path("workflows") / name / "codex/SKILL.md"] = skill
        outputs[Path("workflows") / name / "codex/agents/openai.yaml"] = (
            "# Invoke explicitly with $" + name + ".\npolicy:\n  allow_implicit_invocation: false\n"
        )
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output-dir", type=Path, help="Render into a staging directory instead of the repository")
    parser.add_argument("--check", action="store_true", help="Report missing or stale generated files without writing")
    args = parser.parse_args()
    if args.check and args.output_dir:
        parser.error("--check and --output-dir are mutually exclusive")
    root = args.root.resolve()
    destination = args.output_dir or root
    try:
        outputs = render(root)
        stale = []
        for relative, content in outputs.items():
            path = destination / relative
            if args.check:
                if not path.is_file() or path.read_text() != content:
                    stale.append(str(relative))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
        if stale:
            print("Stale generated files:\n" + "\n".join(stale), file=sys.stderr)
            return 1
    except (OSError, ValueError, KeyError) as error:
        print(f"Generation failed: {error}", file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} adapters.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
